#!/usr/bin/env bash
# Builds agent/clank.mjs, the one-file CLI + MCP server, from
#   agent/src/clank.mjs       the CLI, MCP stdio and MCP HTTP code
#   agent/vendor/clankmail.ts github.com/ZacxDev/clankmail ts/clankmail.ts,
#                             vendored byte for byte at CLANKMAIL_COMMIT
#
#   bash agent/build.sh            # rewrite agent/clank.mjs
#   bash agent/build.sh --check    # fail if agent/clank.mjs is stale
#
# The output depends on the esbuild version, so it is pinned: a different
# esbuild is refused rather than silently producing a different file.
set -euo pipefail

CLANKMAIL_COMMIT=c0161a3
CLANKMAIL_SRC=ts/clankmail.ts
CLANKMAIL_SHA256=8e6ef1ff784af1a2ca1cfa29e64d7135cd983a662351e1c9c91e762040b57df5
ESBUILD_VERSION=0.27.2

here="$(CDPATH= cd -- "$(dirname -- "${BASH_SOURCE[0]}")" >/dev/null && pwd)"
vendor="$here/vendor/clankmail.ts"
out="$here/clank.mjs"

got="$(sha256sum "$vendor" | cut -d' ' -f1)"
if [ "$got" != "$CLANKMAIL_SHA256" ]; then
  echo "agent/vendor/clankmail.ts is not clankmail $CLANKMAIL_COMMIT:$CLANKMAIL_SRC (sha256 $got, want $CLANKMAIL_SHA256)." >&2
  echo "Re-vendor it with: git -C <clankmail> show $CLANKMAIL_COMMIT:$CLANKMAIL_SRC > agent/vendor/clankmail.ts" >&2
  exit 1
fi

run_esbuild() {
  if command -v esbuild >/dev/null 2>&1; then
    command esbuild "$@"
  else
    nix-shell -p esbuild --run "esbuild $(printf ' %q' "$@")"
  fi
}
v="$(run_esbuild --version | tail -1)"
if [ "$v" != "$ESBUILD_VERSION" ]; then
  echo "esbuild $v found; agent/clank.mjs is built with esbuild $ESBUILD_VERSION (bump ESBUILD_VERSION in agent/build.sh and rebuild if you mean to change it)" >&2
  exit 1
fi

banner="#!/usr/bin/env node
// clank.mjs: the Clanksquare CLI and MCP server. Run: node clank.mjs --help
// GENERATED by agent/build.sh from agent/src/clank.mjs; do not edit by hand.
// Includes github.com/ZacxDev/clankmail $CLANKMAIL_SRC at commit $CLANKMAIL_COMMIT
// (sha256 $CLANKMAIL_SHA256). Built with esbuild $ESBUILD_VERSION.
// Source: https://github.com/ZacxDev/clanksquare (Apache-2.0)."

tmp="$(mktemp --suffix=.mjs)"
trap 'rm -f "$tmp"' EXIT
# esbuild writes each input's path, relative to its working directory, into
# the output, so it always runs from the repo root.
cd "$here/.."
run_esbuild agent/src/clank.mjs --bundle --platform=node --format=esm --target=node20 \
  --legal-comments=none --log-level=warning --banner:js="$banner" --outfile="$tmp"

if [ "${1:-}" = "--check" ]; then
  if ! cmp -s "$tmp" "$out"; then
    echo "agent/clank.mjs is stale: run 'make agent' and commit it" >&2
    diff -u "$out" "$tmp" | head -20 >&2 || true
    exit 1
  fi
  echo "agent/clank.mjs is up to date"
else
  cp "$tmp" "$out"
  chmod 644 "$out"
fi
